    public static UiLanguage CurrentLanguage { get; private set; } = UiLanguage.ChineseSimplified;

    public static void Apply(TopLevel root, UiLanguage language)
    {
        ArgumentNullException.ThrowIfNull(root);
        CurrentLanguage = language;
        ApplyTree(root, language);
        NotifySubscribers(language);
    }

    public static string Text(string chinese) => Text(chinese, CurrentLanguage);

    public static string Text(string chinese, UiLanguage language)
    {
        ArgumentNullException.ThrowIfNull(chinese);
        return Translate(chinese, language);
    }

    public static string Format(string chineseFormat, params object?[] arguments) =>
        Format(chineseFormat, CurrentLanguage, arguments);

    public static string Format(
        string chineseFormat,
        UiLanguage language,
        params object?[] arguments)
    {
        ArgumentNullException.ThrowIfNull(chineseFormat);
        ArgumentNullException.ThrowIfNull(arguments);
        return string.Format(CultureInfo.CurrentCulture, Translate(chineseFormat, language), arguments);
    }

    public static void SetText(
        TextBlock target,
        string chineseFormat,
        params object?[] arguments)
    {
        ArgumentNullException.ThrowIfNull(target);
        SetRuntimeValue(
            RuntimeTexts,
            target,
            target.Text,
            chineseFormat,
            arguments,
            value => target.Text = value);
    }

    public static void SetContent(
        ContentControl target,
        string chineseFormat,
        params object?[] arguments)
    {
        ArgumentNullException.ThrowIfNull(target);
        SetRuntimeValue(
            RuntimeContent,
            target,
            target.Content as string,
            chineseFormat,
            arguments,
            value => target.Content = value);
    }

    internal static void Register<T>(T target, Action<T> refresh)
        where T : class
    {
        ArgumentNullException.ThrowIfNull(target);
        ArgumentNullException.ThrowIfNull(refresh);
        lock (SubscriberGate)
        {
            if (++_registrationsSinceCompaction >= SubscriberCompactionInterval)
            {
                CompactSubscribers();
                _registrationsSinceCompaction = 0;
            }

            Subscribers.Add(new WeakLocalizationSubscriber<T>(target, refresh));
        }
    }

    private static void CompactSubscribers()
    {
        for (var index = Subscribers.Count - 1; index >= 0; index--)
        {
            if (!Subscribers[index].IsAlive)
            {
                Subscribers.RemoveAt(index);
            }
        }
    }

    private static void ApplyTree(Control root, UiLanguage language)
    {
        foreach (var item in root.GetLogicalDescendants()
                     .Cast<object>()
                     .Concat(root.GetVisualDescendants())
                     .Prepend(root)
                     .Distinct(ReferenceEqualityComparer.Instance))
        {
            ApplyOne(item, language);
            if (item is ItemsControl itemsControl)
            {
                ItemsControlObservers.GetValue(
                    itemsControl,
                    static value => new ItemsControlObserver(value));
            }
        }
    }

    private static void ApplyOne(object target, UiLanguage language)
    {
        var snapshot = Snapshots.GetValue(target, Capture);
        if (target is Window window)
        {
            snapshot.Title?.Apply(window.Title, value => window.Title = value, language);
        }

        if (target is TextBlock textBlock)
        {
            if (RuntimeTexts.TryGetValue(textBlock, out var runtimeText))
            {
                runtimeText.Apply(textBlock.Text, value => textBlock.Text = value, language);
            }
            else
            {
                snapshot.Text?.Apply(textBlock.Text, value => textBlock.Text = value, language);
            }
        }

        if (target is ContentControl contentControl)
        {
            if (RuntimeContent.TryGetValue(contentControl, out var runtimeContent))
            {
                runtimeContent.Apply(
                    contentControl.Content as string,
                    value => contentControl.Content = value,
                    language);
            }
            else
            {
                snapshot.Content?.Apply(
                    contentControl.Content as string,
                    value => contentControl.Content = value,
                    language);
            }
        }

        if (target is TextBox textBox)
        {
            snapshot.Watermark?.Apply(textBox.Watermark, value => textBox.Watermark = value, language);
        }

        if (target is CalendarDatePicker datePicker)
        {
            snapshot.Watermark?.Apply(datePicker.Watermark, value => datePicker.Watermark = value, language);
        }

        if (target is Control control)
        {
            snapshot.ToolTip?.Apply(
                ToolTip.GetTip(control) as string,
                value => ToolTip.SetTip(control, value),
                language);
        }
    }

    private static TextSnapshot Capture(object target) => new(
        target is Window window
            ? CaptureKnown(window, Window.TitleProperty, window.Title)
            : null,
        target is TextBlock textBlock
            ? CaptureKnown(textBlock, TextBlock.TextProperty, textBlock.Text)
            : null,
        target is ContentControl { Content: string content } contentControl
            ? CaptureKnown(contentControl, ContentControl.ContentProperty, content)
            : null,
        target switch
        {
            TextBox textBox => CaptureKnown(textBox, TextBox.WatermarkProperty, textBox.Watermark),
            CalendarDatePicker picker => CaptureKnown(
                picker,
                CalendarDatePicker.WatermarkProperty,
                picker.Watermark),
            _ => null
        },
        target is Control control && ToolTip.GetTip(control) is string toolTip
            ? CaptureKnown(control, ToolTip.TipProperty, toolTip)
            : null);

    private static LocalizedValue? CaptureKnown(
        AvaloniaObject target,
        AvaloniaProperty property,
        string? value) =>
        value is not null &&
        English.ContainsKey(value) &&
        BindingOperations.GetBindingExpressionBase(target, property) is null
            ? new LocalizedValue(value)
            : null;

    private static void SetRuntimeValue<T>(
        ConditionalWeakTable<T, RuntimeLocalizedValue> values,
        T target,
        string? current,
        string chineseFormat,
        object?[] arguments,
        Action<string> assign)
        where T : class
    {
        ArgumentNullException.ThrowIfNull(chineseFormat);
        ArgumentNullException.ThrowIfNull(arguments);
        var value = values.GetValue(target, static _ => new RuntimeLocalizedValue());
        value.Set(current, chineseFormat, arguments, assign, CurrentLanguage);
    }

    private static void NotifySubscribers(UiLanguage language)
    {
        lock (SubscriberGate)
        {
            for (var index = Subscribers.Count - 1; index >= 0; index--)
            {
                if (!Subscribers[index].Refresh(language))
                {
                    Subscribers.RemoveAt(index);
                }
            }
        }
    }

    private static string Translate(string value, UiLanguage language) => language == UiLanguage.English
        ? English.GetValueOrDefault(value, value)
        : value;

    private sealed record TextSnapshot(
        LocalizedValue? Title,
        LocalizedValue? Text,
        LocalizedValue? Content,
        LocalizedValue? Watermark,
        LocalizedValue? ToolTip);

    private sealed class LocalizedValue(string chineseSource)
    {
        private bool _isDetached;

        public string ChineseSource { get; } = chineseSource;

        public string LastRendered { get; private set; } = chineseSource;

        public void Apply(string? current, Action<string> assign, UiLanguage language)
        {
            if (_isDetached)
            {
                return;
            }

            if (!string.Equals(current, LastRendered, StringComparison.Ordinal))
            {
                _isDetached = true;
                return;
            }

            var rendered = Translate(ChineseSource, language);
            LastRendered = rendered;
            if (!string.Equals(current, rendered, StringComparison.Ordinal))
            {
                assign(rendered);
            }
        }
    }

    private sealed class RuntimeLocalizedValue
    {
        private string _chineseFormat = string.Empty;
        private object?[] _arguments = [];
        private bool _isDetached;

        public string LastRendered { get; private set; } = string.Empty;

        public void Set(
            string? current,
            string chineseFormat,
            object?[] arguments,
            Action<string> assign,
            UiLanguage language)
        {
            _chineseFormat = chineseFormat;
            _arguments = arguments;
            _isDetached = false;
            var rendered = Render(language);
            LastRendered = rendered;
            if (!string.Equals(current, rendered, StringComparison.Ordinal))
            {
                assign(rendered);
            }
        }

        public void Apply(string? current, Action<string> assign, UiLanguage language)
        {
            if (_isDetached)
            {
                return;
            }

            if (!string.Equals(current, LastRendered, StringComparison.Ordinal))
            {
                _isDetached = true;
                return;
            }

            var rendered = Render(language);
            LastRendered = rendered;
            if (!string.Equals(current, rendered, StringComparison.Ordinal))
            {
                assign(rendered);
            }
        }

        private string Render(UiLanguage language) => _arguments.Length == 0
            ? Translate(_chineseFormat, language)
            : Format(_chineseFormat, language, _arguments);
    }

    private interface IWeakLocalizationSubscriber
    {
        bool IsAlive { get; }

        bool Refresh(UiLanguage language);
    }

    private sealed class WeakLocalizationSubscriber<T>(T target, Action<T> refresh)
        : IWeakLocalizationSubscriber
        where T : class
    {
        private readonly WeakReference<T> _target = new(target);

        public bool IsAlive => _target.TryGetTarget(out _);

        public bool Refresh(UiLanguage language)
        {
            if (!_target.TryGetTarget(out var value))
            {
                return false;
            }

            refresh(value);
            return true;
        }
    }

    private sealed class ItemsControlObserver
    {
        private readonly WeakReference<ItemsControl> _itemsControl;

        public ItemsControlObserver(ItemsControl itemsControl)
        {
            _itemsControl = new WeakReference<ItemsControl>(itemsControl);
            itemsControl.ContainerPrepared += OnContainerPrepared;
        }

        private void OnContainerPrepared(object? sender, ContainerPreparedEventArgs eventArgs)
        {
            if (!_itemsControl.TryGetTarget(out _))
            {
                return;
            }

            ApplyTree(eventArgs.Container, CurrentLanguage);
        }
    }
